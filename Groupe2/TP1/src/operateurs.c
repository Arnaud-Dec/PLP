#include <stdio.h>

int main(){

    int a = 16;
    int b = 3;

    //Calculs :
    printf("resultat a+b: %d\n", a+b);
    printf("resultat a-b: %d\n", a-b);

    printf("resultat a*b: %d\n", a*b);
    printf("resultat a/b: %d\n", a/b);

    printf("resultat a modulo b: %d\n", a%b);

    //Comparaisons :
    printf("es que a = b: %d\n", a==b);
    printf("es que a > b: %d\n", a>b);

    return 0;
}

